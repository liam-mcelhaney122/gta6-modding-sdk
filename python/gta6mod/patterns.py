"""Generated-pattern index: load, verify, dump.

``sdk/data/generated/patterns.<build>.json`` is GENERATED by
``sdk/generators/gen_patterns.py`` from ``re-db/builds/<build>/anchors.json``.
The same data is compiled into ``sdk/include/gta6mod/patterns.hpp``.

``python -m gta6mod patterns check <exe>`` is the CI gate: every pattern must
match exactly once and resolve to its recorded RVA. Every signed entry is also
checked a second time with an independent naive scanner (no regex), so a bug in
one matcher does not silently pass.

Xref-chain anchors (no unique signature of their own) carry ``chain``: a unique
start (``from_signature``, or ``from_anchor`` whose recipe is copied into
``from_spec`` so an entry resolves on its own) plus steps
(:func:`gta6mod.pattern.apply_chain`). They are checked like every other entry:
ok or failed, never skipped.

Signatures, not addresses: the runtime rebases by pattern (plan.md Phase 6,
FiveM ``hook::pattern`` / YimMenu model).
"""
from __future__ import annotations

import json
import os
import struct

from . import GAME_BUILD
from .pattern import Pattern, apply_chain, scan
from .paths import sdk_root
from .pe import PEImage

GENERATED_DIR = os.path.join(sdk_root(), "data", "generated")


def index_path(build: str = GAME_BUILD) -> str:
    return os.path.join(GENERATED_DIR, f"patterns.{build}.json")


def load_index(build: str = GAME_BUILD, path: str | None = None) -> tuple[dict, str]:
    p = path or index_path(build)
    with open(p, "r", encoding="utf-8") as fh:
        return json.load(fh), p


def naive_scan(image: PEImage, pattern: Pattern, limit: int = 2) -> list[int]:
    """Independent second matcher: masked compare, prefixed by the longest concrete run.

    Deliberately does not share code with :func:`gta6mod.pattern.scan` (no regex).
    """
    data = image.data
    best_at, best_len = 0, 0
    run_at, run_len = None, 0
    for i, m in enumerate(pattern.mask):
        if m:
            if run_at is None:
                run_at = i
            run_len += 1
            if run_len > best_len:
                best_at, best_len = run_at, run_len
        else:
            run_at, run_len = None, 0
    if not best_len:
        return []
    needle = pattern.data[best_at:best_at + best_len]
    n = len(pattern.data)
    hits: list[int] = []
    for lo, hi in image.code_ranges():
        pos = lo
        while True:
            k = data.find(needle, pos, hi)
            if k < 0:
                break
            base = k - best_at
            if base >= lo and base + n <= hi and all(
                    not m or data[base + i] == b for i, (b, m) in enumerate(zip(pattern.data, pattern.mask))):
                rva = image.off_to_rva(base)
                if rva is not None:
                    hits.append(rva)
                    if len(hits) >= limit:
                        return hits
            pos = k + 1
    return hits


def resolve(image: PEImage, entry: dict) -> tuple[int | None, str]:
    """Return (resolved_rva, status) for one index entry."""
    chain = entry.get("chain")
    if chain:
        if chain.get("from_signature"):
            start, status = _resolve_signed(image, {"signature": chain["from_signature"], "kind": "function"})
        elif chain.get("from_spec"):
            start, status = _resolve_signed(image, chain["from_spec"])
        else:
            return None, "chain-no-start"
        if status != "ok":
            return None, f"chain-from-{status}"
        return apply_chain(image, start, chain.get("steps", []))
    return _resolve_signed(image, entry)


def _resolve_signed(image: PEImage, entry: dict) -> tuple[int | None, str]:
    sig = entry.get("signature")
    if not sig:
        return None, "unsigned"
    pat = Pattern.parse(sig)
    hits = scan(image, pat, limit=2)
    if not hits:
        return None, "not-found"
    if len(hits) > 1:
        return None, "ambiguous"
    second = naive_scan(image, pat)
    if second != hits:
        return None, "matcher-disagree"
    site = hits[0]
    if entry.get("kind") in ("data", "vtable"):
        rip = entry.get("rip")
        if not rip:
            return None, "missing-rip-spec"
        raw = image.read_rva(site + int(rip["disp_at"]), 4)
        if len(raw) != 4:
            return None, "rip-out-of-image"
        target = site + int(rip["insn_len"]) + struct.unpack("<i", raw)[0]
        return target, "ok"
    return site + int(entry.get("offset", 0)), "ok"


def verify_all(image: PEImage, entries: list[dict]) -> list[dict]:
    rows = []
    for e in entries:
        got, status = resolve(image, e)
        expected = e.get("expected_rva")
        if status == "ok" and expected is not None and got != expected:
            status = "moved"
        rows.append({"name": e["name"], "status": status,
                     "expected_rva": expected, "resolved_rva": got,
                     "confidence": e.get("confidence", "low")})
    return rows


def check(exe_path: str, build: str = GAME_BUILD, path: str | None = None) -> int:
    doc, src = load_index(build, path)
    image = PEImage(exe_path)
    entries = doc["patterns"]
    rows = verify_all(image, entries)
    bad = unsigned = 0
    chains = sum(1 for e in entries if e.get("chain"))
    for r in rows:
        if r["status"] == "unsigned":
            unsigned += 1
            continue
        if r["status"] != "ok":
            bad += 1
            exp = "-" if r["expected_rva"] is None else f"{r['expected_rva']:#x}"
            got = "-" if r["resolved_rva"] is None else f"{r['resolved_rva']:#x}"
            print(f"  FAIL {r['status']:16} {r['name']:44} expected {exp:>11} got {got:>11}")
    print(f"{len(rows) - bad - unsigned}/{len(rows)} patterns match exactly once "
          f"({chains} via xref chains, {unsigned} unsigned by design; source {os.path.basename(src)}, exe {image.sha256[:16]}...)")
    if doc.get("exe_sha256") and doc["exe_sha256"] != image.sha256:
        print(f"  note: index was generated for exe {doc['exe_sha256'][:16]}..., not this one")
    return 1 if bad else 0
