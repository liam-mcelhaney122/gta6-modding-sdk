_INDEX = {h: i for i, h in enumerate(ACTION_HASHES)}


def action_index(action: int | str) -> int | None:
    """Index (rage__InputType value) of a script key or INPUT_* name, None if the build has no such action."""
    if isinstance(action, str):
        from .joaat import joaat
        action = joaat(action)
    return _INDEX.get(int(action) & 0xFFFFFFFF)


def action_name(action: int | str) -> str | None:
    """INPUT_* name of an action, None if unnamed or not an action of this build."""
    i = action_index(action)
    return None if i is None else ACTION_NAMES[i]


def is_action(action: int | str) -> bool:
    """True if the value is one of the ACTION_COUNT script keys of this build."""
    return action_index(action) is not None
